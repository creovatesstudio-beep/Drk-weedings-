export function buildDefaultPermissions(): PermissionRecord[] {
  const perms: PermissionRecord[] = [];
  for (const role of INITIAL_ROLES) {
    for (const mod of ALL_MODULES) {
      const isOwner = role.name === 'Owner';
      const isAdmin = role.name === 'Administrator';
      const isFinancialModule = mod === 'invoices' || mod === 'expenses' || mod === 'reports';
      perms.push({
        id: `perm-${role.id}-${mod}`,
        role_id: role.id,
        role_name: role.name as StaffRole,
        module: mod,
        can_view: isOwner || isAdmin || !isFinancialModule,
        can_create: isOwner || isAdmin || mod === 'projects' || mod === 'deliverables',
        can_edit: isOwner || isAdmin || mod === 'projects' || mod === 'deliverables' || mod === 'calendar',
        can_delete: isOwner,
        can_view_financials: isOwner,
      });
    }
  }
  return perms;
}

